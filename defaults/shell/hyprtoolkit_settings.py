#!/usr/bin/env python3
"""Render a complete, owned Hyprtoolkit 0.6 configuration (no sourced fragments)."""
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import gtk_settings

HEADER = '# Generated by Blankweave. Edit this file to take ownership.\n'


def load(name, default):
    path = gtk_settings.config_root() / 'blankweave' / name
    return json.loads(path.read_text()) if path.exists() else default


def owned(text):
    lines = text.splitlines(keepends=True)
    return (len(lines) >= 2 and lines[0] == HEADER
            and lines[1] == '# Content SHA256: ' + hashlib.sha256(''.join(lines[2:]).encode()).hexdigest() + '\n')


def render(theme, interface, accessibility):
    colors = theme['colors']
    scale = interface.get('text_scale', 1)
    if type(scale) not in (int, float) or scale not in (1, 1.15, 1.3):
        raise ValueError('Invalid text scale for Hyprtoolkit.')
    contrast = accessibility.get('high_contrast', False)
    if type(contrast) is not bool:
        raise ValueError('Invalid contrast preference for Hyprtoolkit.')
    dark = theme.get('mode', 'dark') != 'light'
    mapping = {'background': 'canvas', 'base': 'surfaceRaised', 'text': 'text',
               'alternate_base': 'surfaceHover', 'bright_text': 'text', 'link_text': 'accentBright',
               'accent': 'accentBright', 'accent_secondary': 'accent'}
    if contrast:
        colors = {'canvas': '#000000' if dark else '#ffffff', 'surfaceRaised': '#101010' if dark else '#f5f5f5',
                  'surfaceHover': '#242424' if dark else '#dedede', 'text': '#ffffff' if dark else '#000000',
                  'accentBright': '#8ac7ff' if dark else '#003a80', 'accent': '#8ac7ff' if dark else '#003a80'}
    lines = []
    for key, token in mapping.items():
        value = colors[token]
        if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?', value):
            raise ValueError('Invalid Hyprtoolkit palette color.')
        # Picker is an opaque reading surface; avoid wallpaper-dependent text contrast.
        lines.append(f'{key} = rgba({value[1:7]}ff)')
    icon = theme.get('iconTheme', 'Papirus')
    if not isinstance(icon, str) or not re.fullmatch(r'[A-Za-z0-9_. -]+', icon):
        raise ValueError('Invalid Hyprtoolkit icon theme.')
    lines += ['font_family = Atkinson Hyperlegible Next', 'font_family_monospace = JetBrainsMono Nerd Font',
              'icon_theme = ' + icon, 'rounding_large = 10', 'rounding_small = 4']
    for key, size in [('h1_size', 19), ('h2_size', 15), ('h3_size', 13), ('font_size', 11), ('small_font_size', 10)]:
        lines.append(f'{key} = {int(size * scale + 0.5)}')
    body = '\n'.join(lines) + '\n'
    return HEADER + '# Content SHA256: ' + hashlib.sha256(body.encode()).hexdigest() + '\n' + body


def ownership_message():
    path = gtk_settings.config_root() / 'hypr/hyprtoolkit.conf'
    try:
        personal = path.is_symlink() or (path.exists() and (not path.is_file() or not owned(path.read_text())))
    except (OSError, UnicodeError):
        personal = True
    if personal:
        return 'The screen-sharing picker uses your personal Hyprtoolkit configuration; its appearance is not changed by Settings.'
    return ''


def prepare(interface=None, accessibility=None, theme=None):
    path = gtk_settings.config_root() / 'hypr/hyprtoolkit.conf'
    if ownership_message():
        return []  # Personal files and links remain authoritative.
    theme = theme if theme is not None else load('theme.json', None)
    if not theme or 'colors' not in theme:
        return []  # First install has not resolved its palette yet.
    text = render(theme, interface if interface is not None else load('interface.json', {}),
                  accessibility if accessibility is not None else load('accessibility.json', {}))
    return [(path, text)]


def sync():
    # Callers hold interface.lock; GTK lock serializes the file writer as well.
    with gtk_settings.locked():
        message = ownership_message()
        if message:
            print(message, file=sys.stderr)
        gtk_settings.write(prepare())


if __name__ == '__main__':
    try:
        if sys.argv[1:] == ['--check-theme']:
            prepare(theme=json.load(sys.stdin))
        elif not sys.argv[1:]:
            sync()
        else:
            raise ValueError('Usage: hyprtoolkit_settings.py [--check-theme]')
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f'Could not update Hyprtoolkit appearance: {error}', file=sys.stderr)
        sys.exit(1)
