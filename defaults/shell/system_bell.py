"""An explicit, persistent compositor bell preference; independent of GTK sounds."""
import json
import os
import shutil
import subprocess
import time
from settings_support import atomic, config_home, digest, locked, read, run

HEADER = '-- Generated by Blankweave System bell settings.\n'
DEFAULT = {'version': 1, 'enabled': True}


def validate(data):
    if not isinstance(data, dict) or set(data) != set(DEFAULT) or type(data['version']) is not int or data['version'] != 1 or type(data['enabled']) is not bool:
        raise ValueError('Invalid system bell preferences.')
    return data


def render(data):
    validate(data)
    return (HEADER + 'hl.config({ misc = { bell_sound = "' + ('default' if data['enabled'] else 'none') + '" } })\n'
            + '_G.blankweave_bell_revision = "' + digest(data) + '"\n')


class Bell:
    def __init__(self):
        self.directory = config_home() / 'blankweave'
        self.config = self.directory / 'system-bell.json'
        self.rules = self.directory / 'system-bell.lua'
        self.session = os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', '')

    def saved(self):
        return validate(json.loads(read(self.config))) if self.config.exists() else dict(DEFAULT)

    def current(self):
        data = json.loads(run(['hyprctl', 'getoption', 'misc.bell_sound', '-j']))
        if not isinstance(data, dict) or not isinstance(data.get('str'), str):
            raise ValueError('This compositor does not expose a system bell preference.')
        return data['str']

    def marker(self):
        return run(['hyprctl', 'repl', 'return _G.blankweave_bell_revision or "missing"'])

    def status(self):
        result = {'available': False, 'writable': False, 'enabled': False, 'message': '',
                  'revision': '', 'session': self.session, 'current': ''}
        if not self.session or not shutil.which('hyprctl'):
            return dict(result, message='System bell controls require an active Hyprland session.')
        try:
            saved = self.saved()
            current = self.current()
            result.update(available=True, enabled=current not in ('', 'none'), current=current, revision=digest(saved))
            if self.config.is_symlink() or self.rules.is_symlink():
                raise ValueError('Personal system bell preference links are preserved. Edit their source.')
            if self.rules.exists() and read(self.rules) != render(saved):
                raise ValueError('Personal system bell configuration is preserved. Edit its source.')
            expected = digest(saved) if self.config.exists() else 'defaults'
            if self.marker() != expected:
                raise ValueError('System bell preferences are not loaded. Update or reload your desktop configuration.')
            if current != ('default' if saved['enabled'] else 'none'):
                raise ValueError('Personal configuration or another tool overrides the system bell. Resolve that override before editing here.')
            result['writable'] = True
            result['message'] = 'Controls the Wayland system bell only. App event sounds and notifications are separate.'
        except (OSError, ValueError, subprocess.SubprocessError) as error:
            result['message'] = str(error)
        return result

    def reload(self):
        if run(['hyprctl', 'reload', 'config-only']) != 'ok':
            raise ValueError('Hyprland rejected the bell configuration reload.')
        errors = json.loads(run(['hyprctl', 'configerrors', '-j']))
        if not isinstance(errors, list) or any(errors):
            raise ValueError('Hyprland reported configuration errors.')

    def apply(self, request):
        if not isinstance(request, dict) or set(request) != {'enabled', 'revision', 'session', 'current'} or type(request['enabled']) is not bool:
            raise ValueError('Invalid system bell change.')
        with locked('system-bell'):
            before = self.status()
            if not before['writable']:
                raise ValueError(before['message'])
            if any(request[k] != before[k] for k in ('revision', 'session', 'current')):
                raise ValueError('System bell state changed. Refresh before saving.')
            errors = json.loads(run(['hyprctl', 'configerrors', '-j']))
            if not isinstance(errors, list) or any(errors):
                raise ValueError('Resolve existing compositor errors before changing the bell.')
            updated = dict(DEFAULT, enabled=request['enabled'])
            writes = [(self.config, json.dumps(updated, sort_keys=True) + '\n'), (self.rules, render(updated))]
            snapshots = [(path, read(path), content) for path, content in writes]
            try:
                for path, content in writes:
                    atomic(path, content)
                self.reload()
                deadline = time.monotonic() + 2
                while self.marker() != digest(updated) and time.monotonic() < deadline:
                    time.sleep(0.05)
                if self.marker() != digest(updated) or self.current() != ('default' if updated['enabled'] else 'none'):
                    raise ValueError('Personal configuration overrides the requested system bell setting.')
            except (OSError, ValueError, subprocess.SubprocessError) as failure:
                restored = True
                for path, old, written in reversed(snapshots):
                    if path.is_symlink():
                        restored = False
                    elif read(path) == written:
                        if old is None:
                            path.unlink(missing_ok=True)
                        else:
                            atomic(path, old)
                    elif read(path) != old:
                        restored = False
                if restored:
                    try:
                        self.reload()
                        if self.current() != before['current']:
                            raise ValueError('The previous live bell state was not restored.')
                    except (OSError, ValueError, subprocess.SubprocessError):
                        raise ValueError(str(failure) + ' Files restored; reload and inspect the live bell state.') from failure
                raise ValueError(str(failure) + (' Previous settings restored.' if restored else ' Files changed externally; inspect system bell settings.')) from failure
