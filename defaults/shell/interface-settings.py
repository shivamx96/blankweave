#!/usr/bin/env python3
"""Saved text and cursor sizes shared by the shell, theme writer, and compositor."""
from contextlib import contextmanager
import configparser
import fcntl
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import gtk_settings

DEFAULTS = {'version': 1, 'text_scale': 1.0, 'cursor_size': 24}
SCALES = (1.0, 1.15, 1.3)
SIZES = (24, 32, 48)
SCHEMA = 'org.gnome.desktop.interface'


def validate(data):
    if (not isinstance(data, dict) or set(data) != set(DEFAULTS) or type(data['version']) is not int or data['version'] != 1
            or type(data['text_scale']) not in (float, int) or data['text_scale'] not in SCALES
            or type(data['cursor_size']) is not int or data['cursor_size'] not in SIZES):
        raise ValueError('Invalid interface preferences. Check interface.json.')
    return data


def revision(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


def save(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def run(*args):
    result = subprocess.run(args, text=True, capture_output=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or 'Could not apply interface settings.')
    return result.stdout.strip()


def render(data):
    validate(data)
    return ('-- Generated by interface-settings.py. Edit through Settings.\n'
            + 'hl.env("HYPRCURSOR_SIZE", "' + str(data['cursor_size']) + '")\n'
            + 'hl.env("XCURSOR_SIZE", "' + str(data['cursor_size']) + '")\n'
            + '_G.blankweave_interface_revision = "' + revision(data) + '"\n')


class Interface:
    def __init__(self):
        self.directory = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')) / 'blankweave'
        self.config = self.directory / 'interface.json'
        self.rules = self.directory / 'interface.lua'
        self.session = os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', '')

    def settings(self):
        return validate(json.loads(self.config.read_text())) if self.config.exists() else dict(DEFAULTS)

    @contextmanager
    def locked(self):
        self.directory.mkdir(parents=True, exist_ok=True)
        with (self.directory / 'interface.lock').open('a') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise ValueError('Another theme or interface change is in progress. Try again.') from error
            yield

    def marker(self):
        return run('hyprctl', 'repl', 'return _G.blankweave_interface_revision or "missing"')

    def desktop(self):
        scale = float(run('gsettings', 'get', SCHEMA, 'text-scaling-factor'))
        size = int(run('gsettings', 'get', SCHEMA, 'cursor-size'))
        if not math.isfinite(scale) or scale <= 0 or size <= 0:
            raise ValueError('Invalid desktop sizing values.')
        return {'text_scale': scale, 'cursor_size': size}

    def cursor_theme(self):
        data = json.loads((self.directory / 'theme.json').read_text())
        theme = data.get('cursorTheme')
        if not isinstance(theme, str) or not theme or any(ord(c) < 32 for c in theme):
            raise ValueError('Apply a desktop theme before changing the pointer size.')
        return theme

    def status(self):
        saved = self.settings()
        marker = self.marker()
        return {'saved': saved, 'desktop': self.desktop(), 'revision': revision(saved), 'session': self.session,
                'theme': self.cursor_theme(), 'installed': marker != 'missing',
                'synced': marker == (revision(saved) if self.config.exists() else 'defaults')}

    def reload(self):
        if run('hyprctl', 'reload', 'config-only') != 'ok':
            raise ValueError('Hyprland rejected the reload.')
        errors = json.loads(run('hyprctl', 'configerrors', '-j'))
        if not isinstance(errors, list) or any(errors):
            raise ValueError('Resolve Hyprland configuration errors before changing interface settings.')

    def apply(self, request):
        if not isinstance(request, dict) or set(request) != {'revision', 'session', 'desktop', 'theme', 'key', 'value'}:
            raise ValueError('Invalid interface settings request.')
        key = request['key']
        if key not in ('text_scale', 'cursor_size'):
            raise ValueError('Unsupported interface setting.')
        with self.locked(), gtk_settings.locked():
            if self.config.is_symlink() or self.rules.is_symlink():
                raise ValueError('Interface preference symlinks are user-owned.')
            previous = self.settings()
            desktop = self.desktop()
            theme = self.cursor_theme()
            if (not self.session or request['session'] != self.session or request['revision'] != revision(previous)
                    or request['desktop'] != desktop or request['theme'] != theme):
                raise ValueError('Interface or theme settings changed. Refresh and try again.')
            if self.marker() != (revision(previous) if self.config.exists() else 'defaults'):
                raise ValueError('Saved interface settings are not loaded. Reload the desktop first.')
            errors = json.loads(run('hyprctl', 'configerrors', '-j'))
            if not isinstance(errors, list) or any(errors):
                raise ValueError('Resolve existing Hyprland configuration errors first.')
            if self.rules.exists() and self.rules.read_text() != render(previous):
                raise ValueError('interface.lua was edited outside Settings. Its contents were preserved.')
            updated = dict(previous, **{key: request['value']})
            validate(updated)
            gkey = 'text-scaling-factor' if key == 'text_scale' else 'cursor-size'
            if run('gsettings', 'writable', SCHEMA, gkey) != 'true':
                raise ValueError('This desktop setting is read-only.')
            prepared = gtk_settings.prepare({'gtk-cursor-theme-size': str(updated[key])}) if key == 'cursor_size' else []
            writes = [(self.rules, render(updated)), (self.config, json.dumps(updated, sort_keys=True) + '\n')]
            snapshots = [(path, path.read_text() if path.exists() else None, text) for path, text in writes + prepared]
            changed_desktop = False
            try:
                for path, text in writes:
                    save(path, text)
                gtk_settings.write(prepared)
                self.reload()
                deadline = time.monotonic() + 2
                while self.marker() != revision(updated) and time.monotonic() < deadline:
                    time.sleep(0.05)
                if self.marker() != revision(updated):
                    raise ValueError('The desktop did not load saved interface preferences.')
                changed_desktop = True
                if key == 'cursor_size' and run('hyprctl', 'setcursor', theme, str(updated[key])) != 'ok':
                    raise ValueError('Hyprland rejected the pointer size.')
                run('gsettings', 'set', SCHEMA, gkey, str(updated[key]))
                if self.desktop()[key] != updated[key]:
                    raise ValueError('The desktop did not accept the requested size.')
            except (OSError, ValueError, subprocess.SubprocessError) as failure:
                restored = True
                for path, old, written in reversed(snapshots):
                    current = path.read_text() if path.exists() else None
                    if current == written:
                        if old is None: path.unlink()
                        else: gtk_settings.write([(path, old)])
                    elif current != old:
                        restored = False
                try:
                    if restored:
                        self.reload()
                        if changed_desktop:
                            if key == 'cursor_size': run('hyprctl', 'setcursor', theme, str(desktop[key]))
                            run('gsettings', 'set', SCHEMA, gkey, str(desktop[key]))
                except (OSError, ValueError, subprocess.SubprocessError):
                    raise ValueError(str(failure) + ' Recovery incomplete; refresh and reapply the previous size.') from failure
                raise ValueError(str(failure) + (' Previous settings restored.' if restored else ' Files changed externally; refresh and inspect interface settings.')) from failure


def main():
    interface = Interface()
    if sys.argv[1:] == ['status']:
        print(json.dumps(interface.status()))
    elif sys.argv[1:] == ['apply']:
        interface.apply(json.load(sys.stdin))
    else:
        raise ValueError('Usage: interface-settings.py status|apply')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, configparser.Error, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
