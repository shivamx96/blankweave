"""Assistive tools and local accounts, with explicit session ownership."""
import grp
import json
import os
from pathlib import Path
import pwd
import re
from settings_support import atomic, config_home, read, restore
from settings_operations import missing, notice, action, choice, field, installed, privileged, require, run, select, state

TOOLS = {'reader': ('orca', 'Screen reader'), 'keyboard': ('wvkbd-mobintl', 'On-screen keyboard')}
UNITS = config_home() / 'systemd/user'
ZOOM = config_home() / 'blankweave/magnifier.lua'
HEADER = '-- Generated by Blankweave Settings.\n'


def accounts():
    # Restrict administration to local human accounts, not NSS/remote identities.
    local = {line.split(':')[0] for line in Path('/etc/passwd').read_text().splitlines()}
    return [p for p in pwd.getpwall() if p.pw_name in local and 1000 <= p.pw_uid < 65534]


def status(domain):
    if domain == 'accounts':
        rows = accounts()
        admins = set(grp.getgrnam('wheel').gr_mem) if any(g.gr_name == 'wheel' for g in grp.getgrall()) else set()
        options = [choice(p.pw_name) for p in rows]
        actions = [action('create', 'Create local account', [field('name', 'Username'), field('password', 'Initial password', secret=True)], 'Create a standard local account with its own home directory.')]
        if options:
            target = field('name', 'Account', options[0]['value'], options)
            actions += [action('password', 'Change password', [target, field('password', 'New password', secret=True)], 'Change this local account’s password?'),
                        action('role', 'Change account type', [target, field('role', 'Account type', 'standard', [choice('standard'), choice('admin')])], 'Change membership of the administrator group?'),
                        action('delete', 'Remove account', [target], 'Remove this account. Its home directory is retained. Current and last administrator accounts cannot be removed.'),
                        action('signin', 'Set automatic sign-in', [field('enabled', 'Sign-in', 'no', [choice('no', 'Require account password'), choice('yes', 'Automatic sign-in')])], 'Change tty1 sign-in for the current account at next boot. Disk encryption and screen locking are unchanged.')]
        signin = Path('/etc/blankweave/signin.conf')
        return state('Local accounts are managed with administrator authorization. Blankweave uses tty1/UWSM, not a display manager. New users need their own Blankweave setup.',
                     [p.pw_name + (' · administrator' if p.pw_name in admins else ' · standard') for p in rows] + ['Saved sign-in policy: ' + (read(signin) or 'automatic (installer default)').strip()],
                     actions, [(p.pw_name, p.pw_uid, p.pw_name in admins) for p in rows] + [read(signin)], [] if rows else [notice('not-configured', 'No local user accounts found', 'Choose Create local account to add a standard user. Remote and system accounts are not managed here.')])
    details, actions, identities, notices = [], [], [], []
    for key, (executable, label) in TOOLS.items():
        unit = 'blankweave-' + key + '.service'
        present = installed(executable)
        active = run(['systemctl', '--user', 'is-active', unit], codes=(0, 3, 4)) if installed('systemctl') else 'unavailable'
        enabled = (UNITS / 'graphical-session.target.wants' / unit).exists()
        identities.append([key, present, active, enabled])
        details.append(label + ': ' + (active if present else 'not installed') + (' · starts at sign-in' if enabled else ''))
        if not present: notices.append(missing('orca' if key == 'reader' else 'wvkbd'))
        if present:
            actions += [action(key, 'Configure ' + label.lower(), [field('enabled', 'Run tool', 'yes' if active == 'active' else 'no', [choice('yes'), choice('no')], input_type='toggle'),
                         field('startup', 'Start at sign-in', 'yes' if enabled else 'no', [choice('yes'), choice('no')], input_type='toggle')])]
    if installed('hyprctl') and os.environ.get('HYPRLAND_INSTANCE_SIGNATURE'):
        current_zoom = json.loads(run(['hyprctl', 'getoption', 'cursor.zoom_factor', '-j'])).get('float')
        details.append('Current magnification: ' + str(current_zoom))
        identities.append(['zoom', current_zoom, os.environ.get('HYPRLAND_INSTANCE_SIGNATURE')])
        actions.append(action('zoom', 'Set magnification', [field('factor', 'Magnification', '1', [choice('1', 'Off'), choice('1.5', '150%'), choice('2', '200%'), choice('3', '300%')])]))
    if not installed('hyprctl') or not os.environ.get('HYPRLAND_INSTANCE_SIGNATURE'):
        notices.append(notice('unsupported', 'Magnification needs a Hyprland session', 'Sign in to the Blankweave Hyprland desktop to configure magnification.'))
    return state('Magnification is saved for future sessions. Shortcuts can be changed in Keyboard shortcuts: Super+Ctrl+R (reader), Super+Ctrl+K (keyboard), Super+Ctrl+M (reset magnification).', details, actions, [identities, read(ZOOM)], notices)


def apply(domain, request):
    command = request['action']
    if domain == 'accounts':
        if command == 'signin': return privileged('account-signin', enabled=select(request, 'enabled', ['yes', 'no']))
        name = require(request, 'name', r'[a-z_][a-z0-9_-]{0,30}')
        if command != 'create': select(request, 'name', [p.pw_name for p in accounts()])
        values = {'name': name}
        if command in ('create', 'password'): values['password'] = require(request, 'password')
        if command == 'role': values['role'] = select(request, 'role', ['standard', 'admin'])
        return privileged('account-' + command, **values)
    if command in TOOLS:
        executable, label = TOOLS[command]
        if not installed(executable): raise ValueError(label + ' is not installed.')
        enabled = select(request, 'enabled', ['yes', 'no'])
        startup = select(request, 'startup', ['yes', 'no'])
        if command == 'reader' and enabled == 'yes':
            run(['gsettings', 'set', 'org.gnome.desktop.interface', 'toolkit-accessibility', 'true'])
        unit = 'blankweave-' + command + '.service'
        target = UNITS / unit
        old = read(target)
        if old is not None and not old.startswith('# Blankweave assistive tool\n'): raise ValueError('A custom service exists; edit it at its source.')
        text = '# Blankweave assistive tool\n[Unit]\nDescription=' + label + '\nPartOf=graphical-session.target\nAfter=graphical-session-pre.target\n\n[Service]\nExecStart=/usr/bin/' + executable + '\nRestart=on-failure\n\n[Install]\nWantedBy=graphical-session.target\n'
        atomic(target, text)
        run(['systemctl', '--user', 'daemon-reload'])
        run(['systemctl', '--user', 'enable' if startup == 'yes' else 'disable', unit])
        run(['systemctl', '--user', 'start' if enabled == 'yes' else 'stop', unit])
        return label + ': ' + run(['systemctl', '--user', 'is-active', unit], codes=(0, 3, 4))
    if command == 'zoom':
        factor = select(request, 'factor', ['1', '1.5', '2', '3'])
        old = read(ZOOM)
        if old is not None and old not in [HEADER + 'hl.config({ cursor = { zoom_factor = ' + value + ' } })\n' for value in ('1', '1.5', '2', '3')]: raise ValueError('Custom magnifier configuration exists; edit its source.')
        before = json.loads(run(['hyprctl', 'getoption', 'cursor.zoom_factor', '-j'])).get('float')
        if type(before) not in (int, float) or not 1 <= before <= 10: raise ValueError('Cannot read current magnification.')
        lua = 'hl.config({ cursor = { zoom_factor = ' + factor + ' } })'
        text = HEADER + lua + '\n'
        atomic(ZOOM, text)
        try:
            run(['hyprctl', 'eval', lua])
            observed = json.loads(run(['hyprctl', 'getoption', 'cursor.zoom_factor', '-j'])).get('float')
            if observed != float(factor): raise ValueError('The compositor did not apply the requested magnification.')
        except Exception:
            restore(ZOOM, old, text)
            run(['hyprctl', 'eval', 'hl.config({ cursor = { zoom_factor = ' + str(before) + ' } })'])
            raise
        return 'Magnification saved.'
    raise ValueError('Unknown assistive operation.')


def shortcut(tool):
    if tool == 'zoom': return apply('assistive', {'action': 'zoom', 'factor': '1'})
    if tool not in TOOLS: raise ValueError('Unknown assistive tool.')
    unit = 'blankweave-' + tool + '.service'
    active = run(['systemctl', '--user', 'is-active', unit], codes=(0, 3, 4)) == 'active'
    startup = (UNITS / 'graphical-session.target.wants' / unit).exists()
    return apply('assistive', {'action': tool, 'enabled': 'no' if active else 'yes', 'startup': 'yes' if startup else 'no'})


if __name__ == '__main__':
    import sys
    try: shortcut(sys.argv[1])
    except (ValueError, OSError) as error: print(str(error), file=sys.stderr); sys.exit(1)
