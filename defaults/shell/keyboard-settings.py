#!/usr/bin/env python3
"""Persistent XKB layout defaults and identity-checked live layout switching."""
from contextlib import contextmanager
import copy
import fcntl
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

KEYS = ('kb_layout', 'kb_variant', 'kb_options')
HEADER = '-- Generated by keyboard-settings.py. Edit through Blankweave Settings.\n'
EMPTY = {'version': 1, 'values': {}}


def catalog():
    import xml.etree.ElementTree as ET
    rows = []
    tree = ET.parse('/usr/share/X11/xkb/rules/evdev.xml')
    for layout in tree.findall('./layoutList/layout'):
        name = layout.findtext('./configItem/name')
        rows.append({'layout': name, 'variant': '', 'label': layout.findtext('./configItem/description')})
        for variant in layout.findall('./variantList/variant'):
            rows.append({'layout': name, 'variant': variant.findtext('./configItem/name'),
                         'label': variant.findtext('./configItem/description')})
    return rows


def lua(value):
    if isinstance(value, str):
        # JSON strings are not Lua strings (notably \u escapes). Emit UTF-8
        # directly and quote every ASCII control byte with fixed-width escapes.
        return '"' + ''.join('\\' + c if c in '\\"' else f'\\{ord(c):03d}' if ord(c) < 32 else c for c in value) + '"'
    if type(value) is bool:
        return 'true' if value else 'false'
    return str(value)


def validate(data):
    if (not isinstance(data, dict) or set(data) != set(EMPTY)
            or type(data['version']) is not int or data['version'] != 1
            or not isinstance(data['values'], dict)
            or set(data['values']) not in (set(), set(KEYS))):
        raise ValueError('Invalid keyboard preferences.')
    values = data['values']
    if values:
        if any(not isinstance(v, str) or len(v) > 2048 or any(ord(c) < 32 for c in v) for v in values.values()):
            raise ValueError('Invalid keyboard value.')
        layouts, variants = values['kb_layout'].split(','), values['kb_variant'].split(',')
        if not 1 <= len(layouts) <= 4 or len(layouts) != len(variants) or any(not x for x in layouts):
            raise ValueError('Choose between one and four layouts, with matching variants.')
    return data


def revision(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


def render(data):
    validate(data)
    fields = ', '.join(k + ' = ' + lua(v) for k, v in sorted(data['values'].items()))
    return HEADER + 'hl.config({ input = { ' + fields + ' } })\n_G.blankweave_keyboard_revision = ' + lua(revision(data)) + '\n'


def save(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def ipc(*args):
    result = subprocess.run(['hyprctl', *args], text=True, capture_output=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or 'Could not contact Hyprland.')
    return result.stdout.strip()


class Keyboard:
    def __init__(self):
        self.directory = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')) / 'blankweave'
        self.config = self.directory / 'keyboard.json'
        self.rules = self.directory / 'keyboard.lua'
        self.session = os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', '')

    def settings(self):
        return validate(json.loads(self.config.read_text())) if self.config.exists() else copy.deepcopy(EMPTY)

    @contextmanager
    def locked(self):
        self.directory.mkdir(parents=True, exist_ok=True)
        with (self.directory / '.keyboard.lock').open('a') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise ValueError('Another keyboard change is in progress. Try again.') from error
            yield

    def devices(self):
        rows = json.loads(ipc('devices', '-j')).get('keyboards')
        if not isinstance(rows, list) or any(not isinstance(r, dict) or any(not isinstance(r.get(k), str) for k in ('name', 'address', 'layout', 'variant', 'active_keymap')) for r in rows):
            raise ValueError('Invalid keyboard list from Hyprland.')
        return rows

    def values(self):
        keys = (*KEYS, 'kb_file', 'kb_rules', 'kb_model')
        output = ipc('-j', '--batch', '; '.join('getoption input.' + k for k in keys))
        decoder = json.JSONDecoder()
        result = {}
        for key in keys:
            row, offset = decoder.raw_decode(output.lstrip())
            output = output.lstrip()[offset:]
            value = row.get('str')
            if row.get('option') != 'input.' + key or not isinstance(value, str):
                raise ValueError('Invalid keyboard option: ' + key)
            result[key] = '' if value == '[[EMPTY]]' else value
        return result

    def marker(self):
        return ipc('repl', 'return _G.blankweave_keyboard_revision or "missing"')

    def status(self):
        saved = self.settings()
        marker = self.marker()
        expected = revision(saved) if self.config.exists() else 'defaults'
        return {'saved': saved, 'revision': revision(saved), 'session': self.session,
                'values': self.values(), 'devices': self.devices(), 'catalog': catalog(),
                'installed': marker != 'missing', 'synced': marker == expected,
                'message': '' if marker == expected else 'Reload or update the desktop configuration to load saved keyboard settings.'}

    def reload(self):
        if ipc('reload', 'config-only') != 'ok':
            raise ValueError('Hyprland did not accept the configuration reload.')
        errors = json.loads(ipc('configerrors', '-j'))
        if not isinstance(errors, list) or any(errors):
            raise ValueError('Hyprland reported configuration errors after the change.')

    def apply(self, request):
        required = {'revision', 'session', 'values', 'expected'}
        if not isinstance(request, dict) or set(request) != required:
            raise ValueError('Invalid keyboard settings request.')
        updated = validate({'version': 1, 'values': request['values']})
        with self.locked():
            if self.config.is_symlink() or self.rules.is_symlink():
                raise ValueError('Keyboard preference symlinks are user-owned and cannot be edited here.')
            previous = self.settings()
            if request['revision'] != revision(previous) or request['session'] != self.session or not self.session:
                raise ValueError('Keyboard settings or the desktop session changed. Refresh and try again.')
            if self.marker() != (revision(previous) if self.config.exists() else 'defaults'):
                raise ValueError('Saved keyboard settings are not loaded. Reload the desktop first.')
            existing_errors = json.loads(ipc('configerrors', '-j'))
            if not isinstance(existing_errors, list) or any(existing_errors):
                raise ValueError('Resolve the existing Hyprland configuration errors before changing input settings.')
            live = self.values()
            if live != request['expected']:
                raise ValueError('Keyboard configuration changed. Refresh and try again.')
            if live['kb_file'] or live['kb_rules'] not in ('', 'evdev', 'base'):
                raise ValueError('A custom keymap or rules file is active. Manage it in your personal configuration.')
            if updated['values']:
                known = {(r['layout'], r['variant']) for r in catalog()}
                pairs = list(zip(updated['values']['kb_layout'].split(','), updated['values']['kb_variant'].split(',')))
                if any(pair not in known for pair in pairs) or len(set(pairs)) != len(pairs):
                    raise ValueError('Unknown or duplicate keyboard layout/variant.')
                old_options = [o for o in live['kb_options'].split(',') if o and not o.startswith('grp:')]
                new_options = [o for o in updated['values']['kb_options'].split(',') if o and not o.startswith('grp:')]
                groups = [o for o in updated['values']['kb_options'].split(',') if o.startswith('grp:')]
                previous_groups = [o for o in live['kb_options'].split(',') if o.startswith('grp:')]
                if old_options != new_options or (groups != previous_groups and groups not in ([], ['grp:alt_shift_toggle'], ['grp:win_space_toggle'], ['grp:ctrl_shift_toggle'])):
                    raise ValueError('Unsupported shortcut or unrelated keyboard options changed.')
            if self.rules.exists() and self.rules.read_text() != render(previous):
                raise ValueError('keyboard.lua was edited outside Settings. Its contents were preserved.')
            old_config = self.config.read_text() if self.config.exists() else None
            old_rules = self.rules.read_text() if self.rules.exists() else None
            config_text, rules_text = json.dumps(updated, sort_keys=True) + '\n', render(updated)
            try:
                save(self.rules, rules_text)
                save(self.config, config_text)
                self.reload()
                deadline = time.monotonic() + 2
                while self.marker() != revision(updated) and time.monotonic() < deadline:
                    time.sleep(0.05)
                if self.marker() != revision(updated):
                    raise ValueError('The desktop configuration did not load the saved keyboard rules.')
                effective = self.values()
                if updated['values'] and any(effective[k] != v for k, v in updated['values'].items()):
                    raise ValueError('A personal configuration overrides this setting. The change was reverted.')
            except (OSError, ValueError, subprocess.SubprocessError) as failure:
                # Restore only our own writes, never a concurrent external edit.
                restored = True
                for path, written, old in ((self.config, config_text, old_config), (self.rules, rules_text, old_rules)):
                    if path.exists() and path.read_text() == written:
                        if old is None:
                            path.unlink()
                        else:
                            save(path, old)
                    elif (path.read_text() if path.exists() else None) != old:
                        restored = False
                try:
                    if restored:
                        self.reload()
                except (OSError, ValueError, subprocess.SubprocessError):
                    raise ValueError(str(failure) + ' Previous files restored; reload Hyprland to restore the live configuration.') from failure
                raise ValueError(str(failure) + (' Previous settings restored.' if restored else ' Files changed externally; reload and inspect keyboard settings.')) from failure


    def switch(self, request):
        if not isinstance(request, dict) or set(request) != {'session', 'device', 'address', 'layout', 'variant', 'index'}:
            raise ValueError('Invalid layout switch request.')
        with self.locked():
            rows = [r for r in self.devices() if r['name'] == request['device']]
            if (request['session'] != self.session or not self.session or len(rows) != 1
                    or any(rows[0][k] != request[k] for k in ('address', 'layout', 'variant'))):
                raise ValueError('The selected keyboard changed. Refresh and try again.')
            index = request['index']
            if type(index) is not int or not 0 <= index < len(rows[0]['layout'].split(',')):
                raise ValueError('Invalid layout index.')
            if ipc('switchxkblayout', request['device'], str(index)) != 'ok':
                raise ValueError('Hyprland did not accept the layout switch.')
            rows = [r for r in self.devices() if r['name'] == request['device'] and r['address'] == request['address']]
            if len(rows) != 1 or rows[0].get('active_layout_index') != index:
                raise ValueError('The keyboard did not report the requested layout.')


def main():
    keyboard = Keyboard()
    if sys.argv[1:] == ['status']:
        print(json.dumps(keyboard.status()))
    elif sys.argv[1:] == ['apply']:
        keyboard.apply(json.load(sys.stdin))
    elif sys.argv[1:] == ['switch']:
        keyboard.switch(json.load(sys.stdin))
    else:
        raise ValueError('Usage: keyboard-settings.py status|apply|switch')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
