#!/usr/bin/env python3
"""Managed desktop shortcut preferences, conflict checks, and verified rollback."""
from contextlib import contextmanager
import copy
import fcntl
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

HEADER = '-- Generated by shortcuts-settings.py. Edit through Blankweave Settings.\n'
EMPTY = {'version': 1, 'bindings': {}}
MODIFIERS = {'SUPER': 64, 'CTRL': 4, 'ALT': 8, 'SHIFT': 1}
KEYS = list('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789') + ['F' + str(i) for i in range(1, 25)] + [
    'Return', 'Tab', 'Escape', 'space', 'comma', 'period', 'slash', 'minus', 'equal',
    'bracketleft', 'bracketright', 'backslash', 'grave', 'Left', 'Right', 'Up', 'Down',
    'Home', 'End', 'Page_Up', 'Page_Down', 'Insert', 'Delete', 'BackSpace', 'Print',
    'XF86AudioRaiseVolume', 'XF86AudioLowerVolume', 'XF86AudioMute', 'XF86AudioPlay',
    'XF86AudioPause', 'XF86AudioNext', 'XF86AudioPrev', 'XF86MonBrightnessUp', 'XF86MonBrightnessDown']


def catalog():
    return json.loads(Path(__file__).with_name('shortcut-catalog.json').read_text())


def chord(value):
    if not isinstance(value, str) or len(value) > 100:
        raise ValueError('Invalid shortcut.')
    parts = [part.strip() for part in value.split('+')]
    mods, key = parts[:-1], parts[-1]
    keys = {k.lower(): k for k in KEYS}
    if len(mods) != len(set(mods)) or any(m not in MODIFIERS for m in mods) or key.lower() not in keys:
        raise ValueError('Choose a supported key and modifiers.')
    key = keys[key.lower()]
    if not any(m in mods for m in ('SUPER', 'CTRL', 'ALT')) and key not in ['F' + str(i) for i in range(1, 25)] + ['Print'] and not key.startswith('XF86'):
        raise ValueError('Use Super, Ctrl, or Alt with typing and navigation keys.')
    mask = sum(MODIFIERS[m] for m in mods)
    return ' + '.join([m for m in MODIFIERS if m in mods] + [key]), mask, key.lower()


def lua(value):
    if isinstance(value, str):
        # JSON strings are not Lua strings (notably \u escapes). Emit UTF-8
        # directly and quote every ASCII control byte with fixed-width escapes.
        return '"' + ''.join('\\' + c if c in '\\"' else f'\\{ord(c):03d}' if ord(c) < 32 else c for c in value) + '"'
    if type(value) is bool:
        return 'true' if value else 'false'
    return str(value)


def validate(data):
    if (not isinstance(data, dict) or set(data) != set(EMPTY)
            or type(data['version']) is not int or data['version'] != 1
            or not isinstance(data['bindings'], dict)):
        raise ValueError('Invalid shortcut preferences.')
    known = {r['id'] for r in catalog()}
    if any(k not in known for k in data['bindings']):
        raise ValueError('Unknown saved shortcut action.')
    for value in data['bindings'].values():
        chord(value)
    return data


def revision(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


def render(data):
    validate(data)
    fields = ', '.join('[' + lua(k) + '] = ' + lua(v) for k, v in sorted(data['bindings'].items()))
    return HEADER + '_G.blankweave_shortcuts_revision = ' + lua(revision(data)) + '\nreturn { ' + fields + ' }\n'


def save(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def ipc(*args):
    result = subprocess.run(['hyprctl', *args], text=True, capture_output=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or 'Could not contact Hyprland.')
    return result.stdout.strip()


class Shortcuts:
    def __init__(self):
        self.directory = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')) / 'blankweave'
        self.config = self.directory / 'shortcuts.json'
        self.rules = self.directory / 'shortcuts.lua'
        self.session = os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', '')

    def settings(self):
        return validate(json.loads(self.config.read_text())) if self.config.exists() else copy.deepcopy(EMPTY)

    @contextmanager
    def locked(self):
        self.directory.mkdir(parents=True, exist_ok=True)
        with (self.directory / '.shortcuts.lock').open('a') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise ValueError('Another shortcuts change is in progress. Try again.') from error
            yield

    def bindings(self):
        rows = json.loads(ipc('binds', '-j'))
        if not isinstance(rows, list) or any(not isinstance(r, dict) or any(not isinstance(r.get(k), str) for k in ('key', 'description', 'submap')) or type(r.get('modmask')) is not int or type(r.get('keycode')) is not int for r in rows):
            raise ValueError('Invalid shortcut list from Hyprland.')
        return rows

    def matching(self, rows, action):
        return [r for r in rows if r['description'] == 'blankweave:' + action]

    def conflict(self, rows, action, value):
        _, mask, key = chord(value)
        for row in rows:
            if row['description'] == 'blankweave:' + action:
                continue
            if row['submap'] and row.get('submap_universal') not in (True, 'true'):
                continue
            # Reserve keycode binds conservatively: their logical key depends on
            # the active layout. Do not silently steal custom release/media binds.
            if row['modmask'] == mask and (row['key'].lower() == key or row['keycode'] or row.get('catch_all')):
                return row['description'] or row['key'] or 'a personal keycode binding'
        return ''

    def layout_shortcuts(self):
        row = json.loads(ipc('getoption', 'input.kb_options', '-j'))
        if not isinstance(row, dict) or not isinstance(row.get('str'), str):
            raise ValueError('Cannot read keyboard layout shortcuts.')
        return row['str']

    def verified(self, rows, action, value):
        matches = self.matching(rows, action)
        _, mask, key = chord(value)
        return (len(matches) == 1 and matches[0]['modmask'] == mask
                and matches[0]['key'].lower() == key and not matches[0]['submap']
                and not matches[0].get('release') and not matches[0].get('mouse')
                and bool(matches[0].get('repeat')) == next(r['repeat'] for r in catalog() if r['id'] == action)
                and not self.conflict(rows, action, value))

    def marker(self):
        return ipc('repl', 'return _G.blankweave_shortcuts_revision or "missing"')

    def status(self):
        saved = self.settings()
        marker = self.marker()
        expected = revision(saved) if self.config.exists() else 'defaults'
        bindings = self.bindings()
        rows = []
        for row in catalog():
            value = saved['bindings'].get(row['id'], row['default'])
            rows.append(dict(row, value=value, available=self.verified(bindings, row['id'], value),
                             overridden=row['id'] in saved['bindings']))
        return {'saved': saved, 'revision': revision(saved), 'session': self.session,
                'fingerprint': revision([bindings, self.layout_shortcuts()]), 'rows': rows, 'keys': KEYS,
                'other': [dict(key=r['key'], modmask=r['modmask'], keycode=r['keycode'], submap=r['submap'],
                               description=r['description'], release=bool(r.get('release')))
                          for r in bindings if not r['description'].startswith('blankweave:')],
                'installed': marker != 'missing', 'synced': marker == expected,
                'message': '' if marker == expected else 'Reload or update the desktop configuration to load saved shortcuts.'}

    def reload(self):
        if ipc('reload', 'config-only') != 'ok':
            raise ValueError('Hyprland did not accept the configuration reload.')
        errors = json.loads(ipc('configerrors', '-j'))
        if not isinstance(errors, list) or any(errors):
            raise ValueError('Hyprland reported configuration errors after the change.')

    def apply(self, request):
        required = {'revision', 'session', 'id', 'value', 'fingerprint'}
        if not isinstance(request, dict) or set(request) != required:
            raise ValueError('Invalid shortcuts settings request.')
        known = {r['id']: r for r in catalog()}
        action = request['id']
        if not isinstance(action, str) or action not in known:
            raise ValueError('Unknown shortcut action.')
        value = chord(request['value'] if request['value'] is not None else known[action]['default'])[0]
        with self.locked():
            if self.config.is_symlink() or self.rules.is_symlink():
                raise ValueError('Shortcuts preference symlinks are user-owned and cannot be edited here.')
            previous = self.settings()
            if request['revision'] != revision(previous) or request['session'] != self.session or not self.session:
                raise ValueError('Shortcuts settings or the desktop session changed. Refresh and try again.')
            if self.marker() != (revision(previous) if self.config.exists() else 'defaults'):
                raise ValueError('Saved shortcuts settings are not loaded. Reload the desktop first.')
            existing_errors = json.loads(ipc('configerrors', '-j'))
            if not isinstance(existing_errors, list) or any(existing_errors):
                raise ValueError('Resolve the existing Hyprland configuration errors before changing input settings.')
            bindings = self.bindings()
            layout_options = self.layout_shortcuts()
            if revision([bindings, layout_options]) != request['fingerprint']:
                raise ValueError('Live shortcuts changed. Refresh and try again.')
            current = previous['bindings'].get(action, known[action]['default'])
            if not self.verified(bindings, action, current):
                raise ValueError('This shortcut was removed or overridden outside Settings. Resolve it in your personal configuration.')
            conflict = self.conflict(bindings, action, value)
            if conflict:
                raise ValueError('Shortcut conflicts with ' + conflict + '. Choose another combination.')
            group_keys = {'grp:win_space_toggle': 'SUPER + space', 'grp:alt_space_toggle': 'ALT + space',
                          'grp:ctrl_space_toggle': 'CTRL + space'}
            if any(chord(group_keys[o])[1:] == chord(value)[1:] for o in layout_options.split(',') if o in group_keys):
                raise ValueError('Shortcut conflicts with the keyboard layout switcher.')
            updated = copy.deepcopy(previous)
            if request['value'] is None:
                updated['bindings'].pop(action, None)
            else:
                updated['bindings'][action] = value
            if self.rules.exists() and self.rules.read_text() != render(previous):
                raise ValueError('shortcuts.lua was edited outside Settings. Its contents were preserved.')
            old_config = self.config.read_text() if self.config.exists() else None
            old_rules = self.rules.read_text() if self.rules.exists() else None
            config_text, rules_text = json.dumps(updated, sort_keys=True) + '\n', render(updated)
            try:
                save(self.rules, rules_text)
                save(self.config, config_text)
                self.reload()
                deadline = time.monotonic() + 2
                while self.marker() != revision(updated) and time.monotonic() < deadline:
                    time.sleep(0.05)
                if self.marker() != revision(updated):
                    raise ValueError('The desktop configuration did not load the saved shortcuts rules.')
                if not self.verified(self.bindings(), action, value):
                    raise ValueError('A personal configuration overrides or conflicts with this shortcut. The change was reverted.')
            except (OSError, ValueError, subprocess.SubprocessError) as failure:
                # Restore only our own writes, never a concurrent external edit.
                restored = True
                for path, written, old in ((self.config, config_text, old_config), (self.rules, rules_text, old_rules)):
                    if path.exists() and path.read_text() == written:
                        if old is None:
                            path.unlink()
                        else:
                            save(path, old)
                    elif (path.read_text() if path.exists() else None) != old:
                        restored = False
                try:
                    if restored:
                        self.reload()
                except (OSError, ValueError, subprocess.SubprocessError):
                    raise ValueError(str(failure) + ' Previous files restored; reload Hyprland to restore the live configuration.') from failure
                raise ValueError(str(failure) + (' Previous settings restored.' if restored else ' Files changed externally; reload and inspect shortcuts settings.')) from failure



def main():
    shortcuts = Shortcuts()
    if sys.argv[1:] == ['status']:
        print(json.dumps(shortcuts.status()))
    elif sys.argv[1:] == ['apply']:
        shortcuts.apply(json.load(sys.stdin))
    else:
        raise ValueError('Usage: shortcuts-settings.py status|apply')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
