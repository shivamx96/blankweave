#!/usr/bin/env python3
"""Persistent reduced motion and high contrast with verified desktop writes."""
from contextlib import contextmanager
import configparser
import fcntl
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import gtk_settings

DEFAULTS = {'version': 1, 'reduced_motion': False, 'high_contrast': False}
SCHEMA = 'org.gnome.desktop.interface'
A11Y_SCHEMA = 'org.gnome.desktop.a11y.interface'


def validate(data):
    if (not isinstance(data, dict) or set(data) != set(DEFAULTS) or type(data['version']) is not int or data['version'] != 1
            or any(type(data[k]) is not bool for k in ('reduced_motion', 'high_contrast'))):
        raise ValueError('Invalid accessibility preferences. Check accessibility.json.')
    return data


def boolean(value):
    if value not in ('true', 'false'):
        raise ValueError('Invalid desktop accessibility value.')
    return value == 'true'


def revision(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


def save(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def run(*args):
    result = subprocess.run(args, text=True, capture_output=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or 'Could not apply accessibility settings.')
    return result.stdout.strip()


def render(data):
    validate(data)
    return ('-- Generated by accessibility-settings.py. Edit through Settings.\n'
            + 'hl.config({ animations = { enabled = ' + str(not data['reduced_motion']).lower() + ' } })\n'
            + '_G.blankweave_accessibility_revision = "' + revision(data) + '"\n')


class Accessibility:
    def __init__(self):
        self.directory = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')) / 'blankweave'
        self.config = self.directory / 'accessibility.json'
        self.rules = self.directory / 'accessibility.lua'
        self.session = os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', '')

    def settings(self):
        return validate(json.loads(self.config.read_text())) if self.config.exists() else dict(DEFAULTS)

    @contextmanager
    def locked(self):
        self.directory.mkdir(parents=True, exist_ok=True)
        with (self.directory / 'interface.lock').open('a') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise ValueError('Another theme or interface change is in progress. Try again.') from error
            yield

    def marker(self):
        return run('hyprctl', 'repl', 'return _G.blankweave_accessibility_revision or "missing"')

    def desktop(self):
        motion = not boolean(run('gsettings', 'get', SCHEMA, 'enable-animations'))
        contrast = boolean(run('gsettings', 'get', A11Y_SCHEMA, 'high-contrast'))
        row = json.loads(run('hyprctl', 'getoption', 'animations.enabled', '-j'))
        if not isinstance(row, dict) or type(row.get('bool')) is not bool:
            raise ValueError('Cannot read compositor animation state.')
        return {'reduced_motion': motion, 'high_contrast': contrast, 'compositor_motion': not row['bool']}

    def status(self):
        saved = self.settings()
        marker = self.marker()
        return {'saved': saved, 'desktop': self.desktop(), 'revision': revision(saved), 'session': self.session,
                'installed': marker != 'missing',
                'synced': marker == (revision(saved) if self.config.exists() else 'defaults')}

    def reload(self):
        if run('hyprctl', 'reload', 'config-only') != 'ok':
            raise ValueError('Hyprland rejected the reload.')
        errors = json.loads(run('hyprctl', 'configerrors', '-j'))
        if not isinstance(errors, list) or any(errors):
            raise ValueError('Resolve Hyprland configuration errors before changing accessibility settings.')

    def apply(self, request):
        if not isinstance(request, dict) or set(request) != {'revision', 'session', 'desktop', 'key', 'value'}:
            raise ValueError('Invalid accessibility settings request.')
        key = request['key']
        if key not in ('reduced_motion', 'high_contrast'):
            raise ValueError('Unsupported accessibility setting.')
        with self.locked(), gtk_settings.locked():
            if self.config.is_symlink() or self.rules.is_symlink():
                raise ValueError('Accessibility preference symlinks are user-owned.')
            previous = self.settings()
            desktop = self.desktop()
            if (not self.session or request['session'] != self.session or request['revision'] != revision(previous)
                    or request['desktop'] != desktop):
                raise ValueError('Accessibility or theme settings changed. Refresh and try again.')
            if self.marker() != (revision(previous) if self.config.exists() else 'defaults'):
                raise ValueError('Saved accessibility settings are not loaded. Reload the desktop first.')
            errors = json.loads(run('hyprctl', 'configerrors', '-j'))
            if not isinstance(errors, list) or any(errors):
                raise ValueError('Resolve existing Hyprland configuration errors first.')
            if self.rules.exists() and self.rules.read_text() != render(previous):
                raise ValueError('accessibility.lua was edited outside Settings. Its contents were preserved.')
            updated = dict(previous, **{key: request['value']})
            validate(updated)
            schema = SCHEMA if key == 'reduced_motion' else A11Y_SCHEMA
            gkey = 'enable-animations' if key == 'reduced_motion' else 'high-contrast'
            gvalue = not updated[key] if key == 'reduced_motion' else updated[key]
            if run('gsettings', 'writable', schema, gkey) != 'true':
                raise ValueError('This desktop setting is read-only.')
            prepared = gtk_settings.prepare({'gtk-enable-animations': str(not updated[key]).lower()}) if key == 'reduced_motion' else []
            writes = [(self.rules, render(updated)), (self.config, json.dumps(updated, sort_keys=True) + '\n')]
            snapshots = [(path, path.read_text() if path.exists() else None, text) for path, text in writes + prepared]
            changed_desktop = False
            try:
                for path, text in writes:
                    save(path, text)
                gtk_settings.write(prepared)
                self.reload()
                deadline = time.monotonic() + 2
                while self.marker() != revision(updated) and time.monotonic() < deadline:
                    time.sleep(0.05)
                if self.marker() != revision(updated):
                    raise ValueError('The desktop did not load saved accessibility preferences.')
                if key == 'reduced_motion' and self.desktop()['compositor_motion'] != updated[key]:
                    raise ValueError('Personal configuration overrides compositor animations. Change reverted.')
                changed_desktop = True
                run('gsettings', 'set', schema, gkey, str(gvalue).lower())
                if self.desktop()[key] != updated[key]:
                    raise ValueError('The desktop did not accept the accessibility preference.')
            except (OSError, ValueError, subprocess.SubprocessError) as failure:
                restored = True
                for path, old, written in reversed(snapshots):
                    current = path.read_text() if path.exists() else None
                    if current == written:
                        if old is None: path.unlink()
                        else: gtk_settings.write([(path, old)])
                    elif current != old:
                        restored = False
                try:
                    if restored:
                        self.reload()
                        if changed_desktop:
                            old_value = not desktop[key] if key == 'reduced_motion' else desktop[key]
                            run('gsettings', 'set', schema, gkey, str(old_value).lower())
                except (OSError, ValueError, subprocess.SubprocessError):
                    raise ValueError(str(failure) + ' Recovery incomplete; refresh and reapply the previous preference.') from failure
                raise ValueError(str(failure) + (' Previous settings restored.' if restored else ' Files changed externally; refresh and inspect accessibility settings.')) from failure


def main():
    accessibility = Accessibility()
    if sys.argv[1:] == ['status']:
        print(json.dumps(accessibility.status()))
    elif sys.argv[1:] == ['apply']:
        accessibility.apply(json.load(sys.stdin))
    else:
        raise ValueError('Usage: accessibility-settings.py status|apply')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, configparser.Error, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
