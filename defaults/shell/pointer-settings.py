#!/usr/bin/env python3
"""Persistent Hyprland pointer defaults and explicitly selected device overrides."""
from contextlib import contextmanager
import copy
import fcntl
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

FIELDS = {
    'global': {'sensitivity': 'float', 'natural_scroll': 'bool', 'left_handed': 'bool', 'accel_profile': 'str'},
    'touchpad': {'natural_scroll': 'bool', 'tap_to_click': 'bool', 'disable_while_typing': 'bool'},
}
HEADER = '-- Generated by pointer-settings.py. Edit through Blankweave Settings.\n'
EMPTY = {'version': 1, 'global': {}, 'touchpad': {}, 'devices': {}}


def lua(value):
    if isinstance(value, str):
        # JSON strings are not Lua strings (notably \u escapes). Emit UTF-8
        # directly and quote every ASCII control byte with fixed-width escapes.
        return '"' + ''.join('\\' + c if c in '\\"' else f'\\{ord(c):03d}' if ord(c) < 32 else c for c in value) + '"'
    if type(value) is bool:
        return 'true' if value else 'false'
    return str(value)


def valid_value(key, value):
    if key == 'sensitivity':
        return type(value) in (int, float) and math.isfinite(value) and -1 <= value <= 1
    if key == 'accel_profile':
        return value in ('', 'adaptive', 'flat') and isinstance(value, str)
    return type(value) is bool


def validate(data):
    if (not isinstance(data, dict) or set(data) != set(EMPTY)
            or type(data['version']) is not int or data['version'] != 1):
        raise ValueError('Invalid pointer preferences. Check pointer.json.')
    for scope in ('global', 'touchpad'):
        values = data[scope]
        if not isinstance(values, dict) or any(k not in FIELDS[scope] or not valid_value(k, v) for k, v in values.items()):
            raise ValueError('Invalid pointer preferences.')
    if not isinstance(data['devices'], dict) or len(data['devices']) > 100:
        raise ValueError('Invalid saved pointer devices.')
    for name, values in data['devices'].items():
        if (not isinstance(name, str) or not name or len(name) > 256
                or any(ord(c) < 32 for c in name) or not isinstance(values, dict)
                or any(k not in (FIELDS['global'] | FIELDS['touchpad']) or not valid_value(k, v) for k, v in values.items())):
            raise ValueError('Invalid saved device override.')
    return data


def revision(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


def render(data):
    validate(data)
    def fields(values):
        return ', '.join(k + ' = ' + lua(v) for k, v in sorted(values.items()))
    lines = [HEADER.rstrip(), 'hl.config({ input = { ' + fields(data['global'])
             + (', ' if data['global'] else '') + 'touchpad = { ' + fields(data['touchpad']) + ' } } })']
    for name, values in sorted(data['devices'].items()):
        lines.append('hl.device({ name = ' + lua(name) + (', ' + fields(values) if values else '') + ' })')
    lines.append('_G.blankweave_pointer_revision = ' + lua(revision(data)))
    return '\n'.join(lines) + '\n'


def save(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def ipc(*args):
    result = subprocess.run(['hyprctl', *args], text=True, capture_output=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or 'Could not contact Hyprland.')
    return result.stdout.strip()


def device_kinds(sysfs=Path('/sys/class/input'), udev=Path('/run/udev/data')):
    result = {}
    for path in sysfs.glob('event*'):
        try:
            name = (path / 'device/name').read_text().strip().lower().replace(' ', '-')
            dev = (path / 'dev').read_text().strip()
            properties = (udev / ('c' + dev)).read_text().splitlines()
            kind = 'touchpad' if 'E:ID_INPUT_TOUCHPAD=1' in properties else 'mouse' if 'E:ID_INPUT_MOUSE=1' in properties else 'pointer'
            result[name] = kind if name not in result else 'pointer'
        except OSError:
            continue
    return result


class Pointer:
    def __init__(self):
        self.directory = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')) / 'blankweave'
        self.config = self.directory / 'pointer.json'
        self.rules = self.directory / 'pointer.lua'
        self.session = os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', '')

    def settings(self):
        return validate(json.loads(self.config.read_text())) if self.config.exists() else copy.deepcopy(EMPTY)

    @contextmanager
    def locked(self):
        self.directory.mkdir(parents=True, exist_ok=True)
        with (self.directory / '.pointer.lock').open('a') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise ValueError('Another pointer change is in progress. Try again.') from error
            yield

    def devices(self):
        rows = json.loads(ipc('devices', '-j')).get('mice')
        if not isinstance(rows, list):
            raise ValueError('Invalid pointer device list from Hyprland.')
        kinds = device_kinds()
        devices = []
        for row in rows:
            if not isinstance(row, dict) or not isinstance(row.get('name'), str) or not isinstance(row.get('address'), str):
                raise ValueError('Invalid pointer device identity.')
            name = row['name']
            devices.append({'name': name, 'address': row['address'], 'kind': kinds.get(name, 'pointer'),
                            'unique': sum(r.get('name') == name for r in rows) == 1})
        return devices

    def values(self):
        keys = [(scope, key, 'input.' + ('touchpad.' if scope == 'touchpad' else '') + key)
                for scope in FIELDS for key in FIELDS[scope]]
        output = ipc('-j', '--batch', '; '.join('getoption ' + option for _, _, option in keys))
        decoder = json.JSONDecoder()
        result = {'global': {}, 'touchpad': {}}
        for scope, key, option in keys:
            row, offset = decoder.raw_decode(output.lstrip())
            output = output.lstrip()[offset:]
            value = row.get(FIELDS[scope][key])
            if key == 'accel_profile' and value == '[[EMPTY]]':
                value = ''
            valid = isinstance(value, str) if key == 'accel_profile' else valid_value(key, value)
            if row.get('option') != option or not valid:
                raise ValueError('Unsupported or invalid pointer option: ' + option)
            result[scope][key] = value
        return result

    def marker(self):
        return ipc('repl', 'return _G.blankweave_pointer_revision or "missing"')

    def status(self):
        saved = self.settings()
        marker = self.marker()
        expected = revision(saved) if self.config.exists() else 'defaults'
        return {'saved': saved, 'revision': revision(saved), 'session': self.session,
                'values': self.values(), 'devices': self.devices(),
                'installed': marker != 'missing', 'synced': marker == expected,
                'message': '' if marker == expected else 'Reload or update the desktop configuration to load saved pointer settings.'}

    def reload(self):
        if ipc('reload', 'config-only') != 'ok':
            raise ValueError('Hyprland did not accept the configuration reload.')
        errors = json.loads(ipc('configerrors', '-j'))
        if not isinstance(errors, list) or any(errors):
            raise ValueError('Hyprland reported configuration errors after the change.')

    def apply(self, request):
        required = {'revision', 'session', 'scope', 'device', 'address', 'key', 'value'}
        if not isinstance(request, dict) or set(request) != required:
            raise ValueError('Invalid pointer settings request.')
        scope, key, value = request['scope'], request['key'], request['value']
        if (scope not in ('global', 'touchpad', 'device') or not isinstance(key, str)
                or any(not isinstance(request[k], str) for k in ('revision', 'session', 'device', 'address'))):
            raise ValueError('Invalid pointer scope.')
        with self.locked():
            if self.config.is_symlink() or self.rules.is_symlink():
                raise ValueError('Pointer preference symlinks are user-owned and cannot be edited here.')
            previous = self.settings()
            if request['revision'] != revision(previous) or request['session'] != self.session or not self.session:
                raise ValueError('Pointer settings or the desktop session changed. Refresh and try again.')
            if self.marker() != (revision(previous) if self.config.exists() else 'defaults'):
                raise ValueError('Saved pointer settings are not loaded. Reload the desktop first.')
            existing_errors = json.loads(ipc('configerrors', '-j'))
            if not isinstance(existing_errors, list) or any(existing_errors):
                raise ValueError('Resolve the existing Hyprland configuration errors before changing input settings.')
            if scope == 'device':
                matches = [d for d in self.devices() if d['name'] == request['device'] and d['address'] == request['address']]
                if len(matches) != 1 or not matches[0]['unique']:
                    raise ValueError('The selected device changed or is ambiguous. Select it again.')
                allowed = FIELDS['global'] | (FIELDS['touchpad'] if matches[0]['kind'] == 'touchpad' else {})
            else:
                allowed = FIELDS[scope]
            if key not in allowed or (value is not None and not valid_value(key, value)):
                raise ValueError('Unsupported pointer setting or value.')
            if self.rules.exists() and self.rules.read_text() != render(previous):
                raise ValueError('pointer.lua was edited outside Settings. Its contents were preserved.')
            updated = copy.deepcopy(previous)
            target = updated['devices'].setdefault(request['device'], {}) if scope == 'device' else updated[scope]
            if value is None:
                target.pop(key, None)
            else:
                target[key] = value
            if scope == 'device' and not target:
                updated['devices'].pop(request['device'], None)
            validate(updated)
            old_config = self.config.read_text() if self.config.exists() else None
            old_rules = self.rules.read_text() if self.rules.exists() else None
            config_text, rules_text = json.dumps(updated, sort_keys=True) + '\n', render(updated)
            try:
                save(self.rules, rules_text)
                save(self.config, config_text)
                self.reload()
                deadline = time.monotonic() + 2
                while self.marker() != revision(updated) and time.monotonic() < deadline:
                    time.sleep(0.05)
                if self.marker() != revision(updated):
                    raise ValueError('The desktop configuration did not load the saved pointer rules.')
                if scope != 'device' and value is not None and self.values()[scope][key] != value:
                    raise ValueError('A personal configuration overrides this setting. The change was reverted.')
                if scope == 'device' and not any(d['name'] == request['device'] and d['address'] == request['address'] for d in self.devices()):
                    raise ValueError('The selected device disconnected during the change.')
            except (OSError, ValueError, subprocess.SubprocessError) as failure:
                # Restore only our own writes, never a concurrent external edit.
                restored = True
                for path, written, old in ((self.config, config_text, old_config), (self.rules, rules_text, old_rules)):
                    if path.exists() and path.read_text() == written:
                        if old is None:
                            path.unlink()
                        else:
                            save(path, old)
                    elif (path.read_text() if path.exists() else None) != old:
                        restored = False
                try:
                    if restored:
                        self.reload()
                except (OSError, ValueError, subprocess.SubprocessError):
                    raise ValueError(str(failure) + ' Previous files restored; reload Hyprland to restore the live configuration.') from failure
                raise ValueError(str(failure) + (' Previous settings restored.' if restored else ' Files changed externally; reload and inspect pointer settings.')) from failure


def main():
    pointer = Pointer()
    if sys.argv[1:] == ['status']:
        print(json.dumps(pointer.status()))
    elif sys.argv[1:] == ['apply']:
        pointer.apply(json.load(sys.stdin))
    else:
        raise ValueError('Usage: pointer-settings.py status|apply')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
